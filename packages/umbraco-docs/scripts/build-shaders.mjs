// Prepares the hero's WGSL into src/hero/shaders.generated.ts, so sites get ready-to-use shader
// data and need no WGSL loader in their own build. Build machines have no GPU, so this skips
// device validation; check the shaders locally with `pnpm exec vgpu check <file> --require-validation`.

import { readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { prepareShader } from "@vgpu/wgsl/prepare";
import { resolveShader } from "@vgpu/wgsl/runtime";

const directory = new URL("../src/hero/shaders/", import.meta.url);
const output = new URL("../src/hero/shaders.generated.ts", import.meta.url);

const names = (await readdir(directory)).filter((file) => file.endsWith(".wgsl")).sort();
const exports = [];
for (const file of names) {
  const entry = fileURLToPath(new URL(file, directory));
  const shader = prepareShader(await resolveShader({ entry, validate: "off", minify: true }), entry);
  exports.push(`export const ${file.replace(/\.wgsl$/, "")}: ShaderSource = ${JSON.stringify(shader)};`);
}

await writeFile(output, `// Generated by scripts/build-shaders.mjs from src/hero/shaders. Do not edit.\nimport type { ShaderSource } from "vgpu";\n\n${exports.join("\n")}\n`);
console.log(`Prepared ${names.length} hero shaders.`);
